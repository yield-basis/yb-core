# --- keystore helpers --------------------------------------------------------

def _keystore_path(name: str) -> str:
    return os.path.expanduser(
        os.path.join("~", ".brownie", "accounts", name + ".json"))


def keystore_address(name: str) -> str:
    with open(_keystore_path(name)) as f:
        return to_checksum_address("0x" + json.load(f)["address"])


def account_load(name: str):
    with open(_keystore_path(name)) as f:
        pkey = account.decode_keyfile_json(json.load(f), getpass())
    return account.Account.from_key(pkey)


# --- contract handles --------------------------------------------------------

def load_contracts():
    factory = boa.load_partial("contracts/Factory.vy").at(YB_FACTORY)
    # The migrator MUST be wired to the live Factory admin, whatever it is now.
    factory_owner = boa.load_partial("contracts/HybridFactoryOwner.vy").at(
        factory.admin())
    voting = boa.load_abi(
        os.path.join(ABI_DIR, "TokenVoting.abi.json"), name="AragonVoting"
    ).at(VOTING_PLUGIN)
    ve = boa.load_partial("contracts/dao/VotingEscrow.vy").at(
        voting.getVotingToken())
    return factory, factory_owner, voting, ve


# --- forked-test: passing + executing a vote ---------------------------------

def pass_vote(voting, pid: int):
    cast = 0
    for voter in TEST_VOTERS:
        if voting.isMinParticipationReached(pid):
            break
        if not voting.canVote(pid, voter, VOTE_YES):
            continue
        with boa.env.prank(voter):
            voting.vote(pid, VOTE_YES, False)
        cast += 1
    if not voting.isMinParticipationReached(pid):
        raise RuntimeError(f"Proposal {pid} did not reach quorum "
                           f"({cast} whales voted)")
    print(f"    {cast} whale(s) voted YES; quorum reached")


# --- the swap vote -----------------------------------------------------------

def build_vote_actions(factory, factory_owner, new_migrator: str) -> list:
    actions = [
        Action(to=factory_owner.address, value=0,
               data=factory_owner.set_limit_setter.prepare_calldata(
                   new_migrator, True)),
        Action(to=factory_owner.address, value=0,
               data=factory_owner.set_limit_setter.prepare_calldata(
                   VULNERABLE_LT_MIGRATOR, False)),
    ]
    for market_id in sorted(TARGET_CAP_USD):
        allocation = 2 * TARGET_CAP_USD[market_id] * 10**18
        actions.append(Action(
            to=factory_owner.address, value=0,
            data=factory_owner.lt_allocate_stablecoins.prepare_calldata(
                factory.markets(market_id).lt, allocation)))
    return actions


def vote_metadata(new_migrator: str, factory_owner: str) -> dict:
    """Deliberately terse. This is pinned to IPFS at creation and is public for
    the whole vote duration -- i.e. while the current migrator is still
    registered -- so it does not describe the defect. Publish the detail once the
    proposal has executed."""
    caps = ", ".join(f"market {m} ${TARGET_CAP_USD[m]:,}"
                     for m in sorted(TARGET_CAP_USD))
    return {
        "title": "YB v3: replace the LTMigrator and re-pin market caps",
        "summary": (
            f"Register the rebuilt LTMigrator {new_migrator} as a limit setter "
            f"on the Factory owner {factory_owner} and disable the current one "
            f"({VULNERABLE_LT_MIGRATOR}); the rebuild tightens the argument "
            "validation in migrate_plain/migrate_staked. Then re-pin the "
            f"crvUSD allocations behind the market deposit caps ({caps}), which "
            "leaves them where they are meant to be. Migration behaviour is "
            "otherwise unchanged; deposits, withdrawals and swaps are "
            "unaffected."
        ),
        "resources": [],
    }


# --- IPFS / Etherscan --------------------------------------------------------

def pin_to_ipfs(content: dict) -> str:
    response = requests.post(
        "https://api.pinata.cloud/pinning/pinJSONToIPFS",
        json={"pinataContent": content,
              "pinataMetadata": {"name": "pinnie.json"},
              "pinataOptions": {"cidVersion": 1}},
        headers={"Authorization": f"Bearer {PINATA_TOKEN}",
                 "Content-Type": "application/json"},
        timeout=30,
    )
    assert 200 <= response.status_code < 400, response.text
    return "ipfs://" + response.json()["IpfsHash"]


def verify_on_etherscan(contract, etherscan):
    while True:
        try:
            sleep(VERIFY_RETRY_SECONDS)
            boa_verify(contract, etherscan, wait=True)
            return
        except ValueError as e:
            print(e)
            if "Already Verified" in str(e):
                return


# --- forked-test helpers -----------------------------------------------------

def _fund(lt, to, amount):
    """Source LT shares from the market's gauge -- no reliance on a live holder."""
    with boa.env.prank(lt.staker()):
        lt.transfer(to, amount)


def _same_lt_attack(factory, migrator, market_id):
    """Run the same-LT migration against one market; return (before, after)."""
    lt = boa.load_partial("contracts/LT.vy").at(factory.markets(market_id).lt)
    attacker = boa.env.generate_address()
    _fund(lt, attacker, DUST)
    before = lt.stablecoin_allocation()
    with boa.env.prank(attacker):
        lt.approve(migrator.address, 2**256 - 1)
        migrator.migrate_plain(lt.address, lt.address, DUST, 0)
    return before, lt.stablecoin_allocation()


ASSET_ABI = """[
 {"name":"decimals","outputs":[{"type":"uint8"}],"inputs":[],"stateMutability":"view","type":"function"},
 {"name":"balanceOf","outputs":[{"type":"uint256"}],"inputs":[{"type":"address","name":"a"}],"stateMutability":"view","type":"function"},
 {"name":"approve","outputs":[{"type":"bool"}],"inputs":[{"type":"address","name":"s"},{"type":"uint256","name":"v"}],"stateMutability":"nonpayable","type":"function"}
]"""
POOL_ABI = """[
 {"name":"price_oracle","outputs":[{"type":"uint256"}],"inputs":[],"stateMutability":"view","type":"function"}
]"""


def _deposit_works(factory, market_id) -> bool:
    """Can an ordinary new depositor still enter this market?"""
    lt = boa.load_partial("contracts/LT.vy").at(factory.markets(market_id).lt)
    asset = boa.loads_abi(ASSET_ABI).at(lt.ASSET_TOKEN())
    pool = boa.loads_abi(POOL_ABI).at(lt.CRYPTOPOOL())
    unit = 10 ** asset.decimals()
    user = boa.env.generate_address()
    amount = unit // 10
    boa.deal(asset, user, amount, adjust_supply=False)
    try:
        with boa.env.prank(user):
            asset.approve(lt.address, 2**256 - 1)
            lt.deposit(amount, amount * pool.price_oracle() // unit, 0, user)
        return True
    except Exception:
        return False


def _same_lt_attack_fails(factory, migrator, market_id):
    """The same call, expected to revert without moving the allocation."""
    lt = boa.load_partial("contracts/LT.vy").at(factory.markets(market_id).lt)
    attacker = boa.env.generate_address()
    _fund(lt, attacker, DUST)
    before = lt.stablecoin_allocation()
    with boa.env.prank(attacker):
        lt.approve(migrator.address, 2**256 - 1)
        try:
            migrator.migrate_plain(lt.address, lt.address, DUST, 0)
            raise AssertionError(
                f"market {market_id}: same-LT migration was NOT rejected")
        except AssertionError:
            raise
        except Exception:
            pass
    assert lt.stablecoin_allocation() == before, (
        f"market {market_id}: allocation moved despite the rejection")


# --- entrypoints -------------------------------------------------------------

def run_test():
    boa.fork(NETWORK, block_identifier="latest")
    factory, factory_owner, voting, ve = load_contracts()
    print(f"  current Factory owner: {factory_owner.address}")
    assert factory_owner.limit_setters(VULNERABLE_LT_MIGRATOR), (
        f"{VULNERABLE_LT_MIGRATOR} is not a limit_setter on the current owner — "
        "hardcoded address/state is wrong?")

    vulnerable = boa.load_partial("contracts/LTMigrator.vy").at(
        VULNERABLE_LT_MIGRATOR)

    print("\n=== Reproducing the attack through the DEPLOYED migrator ===")
    for market_id in LIVE_MARKETS:
        with boa.env.anchor():
            before, after = _same_lt_attack(factory, vulnerable, market_id)
            assert after < before, (
                f"market {market_id}: expected the aliased restore to cut the "
                "allocation — is this still the vulnerable migrator?")
            print(f"  market {market_id:>2}: allocation "
                  f"{before / 1e18:>14,.0f} -> {after / 1e18:>14,.0f}  "
                  f"({(after - before) / 1e18:+,.0f} crvUSD)")

    print("\n=== Leaving one market griefed, so the re-pin is exercised ===")
    before, after = _same_lt_attack(factory, vulnerable, FORWARD_TO)
    assert not _deposit_works(factory, FORWARD_TO), (
        f"market {FORWARD_TO} still takes deposits after the cut?")
    print(f"  market {FORWARD_TO}: allocation {before / 1e18:,.0f} -> "
          f"{after / 1e18:,.0f}, deposits blocked")

    print("\n=== Deploying the fixed LTMigrator ===")
    new_migrator = boa.load(
        "contracts/LTMigrator.vy", factory.STABLECOIN(), factory_owner.address)
    assert new_migrator.FACTORY_OWNER().lower() == factory_owner.address.lower()
    print(f"  new migrator: {new_migrator.address}")

    print("\n=== Checkpointing VotingEscrow ===")
    ve.checkpoint()

    proposer = keystore_address(PROPOSER_KEYSTORE)
    print(f"\n=== Creating the swap vote from {PROPOSER_KEYSTORE} "
          f"({proposer}) ===")
    actions = build_vote_actions(factory, factory_owner, new_migrator.address)
    with boa.env.prank(proposer):
        pid = voting.createProposal(*Proposal(
            metadata=b"", actions=actions, allowFailureMap=0,
            startDate=0, endDate=0, voteOption=0, tryEarlyExecution=True))
    print(f"  created proposal {pid}")

    print("\n=== Passing and executing the swap vote ===")
    pass_vote(voting, pid)
    boa.env.time_travel(seconds=voting.minDuration() + 3600)
    assert voting.canExecute(pid), "swap vote cannot execute"
    voting.execute(pid)

    print("\n=== Post-execution state ===")
    new_is = factory_owner.limit_setters(new_migrator.address)
    old_is = factory_owner.limit_setters(VULNERABLE_LT_MIGRATOR)
    print(f"  limit_setters[fixed      {new_migrator.address}] = {new_is}")
    print(f"  limit_setters[vulnerable {VULNERABLE_LT_MIGRATOR}] = {old_is}")
    assert new_is and not old_is, "swap state mismatch"

    print("\n=== Allocations re-pinned ===")
    for market_id in LIVE_MARKETS:
        lt = boa.load_partial("contracts/LT.vy").at(factory.markets(market_id).lt)
        amm = boa.load_partial("contracts/AMM.vy").at(lt.amm())
        target = 2 * TARGET_CAP_USD[market_id] * 10**18
        assert lt.stablecoin_allocation() >= target, (
            f"market {market_id}: allocation below the pinned target")
        # A market whose value has grown into its cap takes no deposits -- that is
        # the designed behaviour, not a leftover of the cut. Only require deposits
        # to reopen where the pinned cap actually leaves headroom.
        value = amm.value_oracle().value
        has_headroom = target // 2 > value
        works = _deposit_works(factory, market_id)
        if has_headroom:
            assert works, (
                f"market {market_id}: deposits still blocked despite cap headroom")
        note = "deposits OK" if works else "AT CAP (raise TARGET_CAP_USD to reopen)"
        print(f"  market {market_id:>2}: allocation "
              f"{lt.stablecoin_allocation() / 1e18:>13,.0f}  "
              f"value {value / 1e18:>13,.0f}  {note}")

    print("\n=== The attack is dead through both migrators ===")
    for market_id in LIVE_MARKETS:
        with boa.env.anchor():
            # Rejected by the guard in the fixed migrator...
            _same_lt_attack_fails(factory, new_migrator, market_id)
            # ...and by the owner in the old one, which is no longer a limit setter.
            _same_lt_attack_fails(factory, vulnerable, market_id)
            print(f"  market {market_id:>2}: rejected by both, allocation untouched")

    print("\n=== An ordinary forward migration still works ===")
    lt_from = boa.load_partial("contracts/LT.vy").at(
        factory.markets(FORWARD_FROM).lt)
    lt_to = boa.load_partial("contracts/LT.vy").at(
        factory.markets(FORWARD_TO).lt)
    user = boa.env.generate_address()
    _fund(lt_from, user, DUST)
    to_alloc = lt_to.stablecoin_allocation()
    with boa.env.prank(user):
        lt_from.approve(new_migrator.address, 2**256 - 1)
        new_migrator.migrate_plain(lt_from.address, lt_to.address, DUST, 0)
    received = lt_to.balanceOf(user)
    assert received > 0, "migration produced no destination shares"
    assert lt_to.stablecoin_allocation() == to_alloc, (
        "destination allocation not restored")
    print(f"  market {FORWARD_FROM} -> {FORWARD_TO}: migrated {DUST} lt_from, "
          f"received {received} lt_to, destination allocation restored")
    print("\nMigrator fix + swap works end-to-end.")


def run_prod():
    boa.set_network_env(NETWORK)
    boa.env.add_account(account_load(PROPOSER_KEYSTORE), force_eoa=True)
    factory, factory_owner, voting, ve = load_contracts()
    print(f"  current Factory owner: {factory_owner.address}")

    etherscan = Etherscan(api_key=ETHERSCAN_API_KEY)
    print("=== Deploying the fixed LTMigrator ===")
    new_migrator = boa.load(
        "contracts/LTMigrator.vy", factory.STABLECOIN(), factory_owner.address)
    print(f"  new migrator: {new_migrator.address}")

    print(f"\n=== Verifying {new_migrator.address} on Etherscan ===")
    verify_on_etherscan(new_migrator, etherscan)
    print("  verified")

    print("\n=== Checkpointing VotingEscrow ===")
    ve.checkpoint()

    print("=== Creating the swap vote ===")
    metadata = pin_to_ipfs(
        vote_metadata(new_migrator.address, factory_owner.address)).encode()
    pid = voting.createProposal(*Proposal(
        metadata=metadata,
        actions=build_vote_actions(factory, factory_owner, new_migrator.address),
        allowFailureMap=0,
        startDate=0, endDate=0, voteOption=0, tryEarlyExecution=True))
    print(f"Created proposal: {pid}")
    print("\nAfter execution: point the front-end at the new migrator address.")


if __name__ == "__main__":
    if "--test" in sys.argv[1:]:
        run_test()
    else:
        run_prod()
