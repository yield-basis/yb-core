#!/usr/bin/env python3
"""
Deploy a fixed LTMigrator and create a YB DAO vote that swaps it in for the
currently-registered one, which allows a same-LT migration.

Why this is needed
------------------
_migrate_plain() never required lt_from != lt_to. With the two aliased, the
lt_from deallocation is read back as lt_to's "previous" allocation and restored
as such at the end of the call, so ANY holder of dust in a live market can
permanently cut that market's crvUSD allocation down to HybridFactoryOwner's
95%-of-collateral bound. Because LT.allocate_stablecoins() transfers the
difference back to the Factory, this also pulls the crvUSD out of the market's
AMM. LT.deposit() then fails its `amm.max_debt() // 2 >= v.value` cap check
("Debt too high") until the DAO re-allocates, and the attack is repeatable.

Measured on a fork at head, per live market, for a few cents of dust:
    market  7 (WBTC) : allocation -40.34M, cap 3.09x -> 1.84x equity
    market  8 (cbBTC): allocation -46.30M, cap 3.51x -> 1.88x equity
    market  9 (tBTC) : allocation  -2.51M, cap 1.98x -> 1.84x equity
    market 10 (WETH) : allocation -13.53M, cap 2.39x -> 1.89x equity
Withdrawals, AMM exchanges in both directions and fee collection keep working --
this is a deposit outage plus a crvUSD relocation, not an unusable AMM.

The fix (two changes, contracts/LTMigrator.vy):
  * assert lt_from.address != lt_to.address in _migrate_plain (covers both
    migrate_plain and migrate_staked) and in _preview_migrate_plain, so the
    views fail early too;
  * snapshot lt_to.stablecoin_allocation() BEFORE the lt_from deallocation, so
    the restore can never write back a value the call itself lowered. The write
    to lt_to stays where it was -- only the read moves.
The lt_from deallocation block is left exactly as it is.

The migrator is immutable and holds no state worth keeping, so the fix ships as
a redeploy. Registering it as a limit setter is ADMIN-only on the owner, and
that ADMIN is the DAO, so this REQUIRES A DAO VOTE. Both the enable (fixed) and
the disable (vulnerable) happen inside one proposal so the swap is atomic and
there is no window in either direction.

Usage:
  python scripts/voting/create_vote_migrator_same_lt_fix.py          # prod
  python scripts/voting/create_vote_migrator_same_lt_fix.py --test   # fork

--test forks mainnet at head, reproduces the attack through the deployed
migrator, deploys the fixed one, creates + passes + executes this swap proposal,
then asserts the attack is dead through both migrators and that an ordinary
forward migration still works.
"""
